/// 魔力の相。マナのマスも、魔導士も、これを1つ持つ。
///
/// **呼び名は色そのもの。** 熱・冷・雷という元素の名前だった頃は、盾のように
/// 元素と関係のない力を持つ魔導士を並べたときに「なぜこの人が雷なのか」が
/// 説明できなかった。相が決めているのは盤面に出る色と、継げるかどうかだけ
/// なので、見たままの色で呼ぶ。
///
/// 盤面に出るのは**編成に含まれる相だけ**。誰を連れていくかが、そのまま
/// 盤面の色数になる。1種類だけの編成が禁じられているのは、同じ相どうしは
/// 継げない以上、1色の盤面では鎖が1枚も編めないため。
///
/// 相が2つだった頃は「赤と青は数学的に排他だから交互に継がれる」という
/// 説明だったが、3つ以上では成り立たない。代わりに
/// **「N 枚ぶんの窓の中に同じ相は二度現れない」** を規則にしてある。
/// 相が2つのときはこれが「交互」と完全に同じ意味になるので、それまでの
/// 盤面と規則は変わらない（README 第7段階）。
///
/// ここは呼び名と並びだけを持つ。色は `ui/theme.dart`、魔導士との対応は
/// `party.dart`、盤面での扱いは `board.dart` が持つ。
library;

enum Phase {
  /// 赤の相。暖色。
  red('赤'),

  /// 青の相。寒色。
  blue('青'),

  /// 紫の相。3つ目として足した相。暖色とも寒色とも離れている。
  violet('紫');

  const Phase(this.label);

  /// 画面に出す一文字。
  final String label;
}
